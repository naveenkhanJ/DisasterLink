/**
 * gen-district-outlines.mjs — writes src/location/districtOutlines.ts from the officer map's outlines.
 *
 * Run from mobile/:  node scripts/gen-district-outlines.mjs
 * Reads  ../backend/src/main/resources/static/js/districts.js  (window.LKA_DISTRICTS, keyed by the
 * district's name, for example "Nuwara Eliya") and writes the TypeScript module keyed by the `District`
 * enum constant of the server (the upper-snake of the name: "Nuwara Eliya" -> NUWARA_ELIYA). Every name
 * maps this way, so there is no explicit map; the script stops if a name does not give one of the 25
 * constants or a constant has no outline.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../backend/src/main/resources/static/js/districts.js');
const target = resolve(here, '../src/location/districtOutlines.ts');

/** The 25 constants of the server's `District` enum (shared/domain/District.java), in its order. */
const DISTRICTS = [
  'AMPARA', 'ANURADHAPURA', 'BADULLA', 'BATTICALOA', 'COLOMBO', 'GALLE', 'GAMPAHA', 'HAMBANTOTA',
  'JAFFNA', 'KALUTARA', 'KANDY', 'KEGALLE', 'KILINOCHCHI', 'KURUNEGALA', 'MANNAR', 'MATALE',
  'MATARA', 'MONARAGALA', 'MULLAITIVU', 'NUWARA_ELIYA', 'POLONNARUWA', 'PUTTALAM', 'RATNAPURA',
  'TRINCOMALEE', 'VAVUNIYA',
];

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(source, 'utf8'), sandbox);
const byName = sandbox.window.LKA_DISTRICTS;

const outlines = new Map();
for (const [name, rings] of Object.entries(byName)) {
  const constant = name.trim().toUpperCase().replace(/\s+/g, '_');
  if (!DISTRICTS.includes(constant)) {
    throw new Error(`The outline "${name}" does not map to a District constant (${constant}).`);
  }
  outlines.set(constant, rings);
}
const missing = DISTRICTS.filter((constant) => !outlines.has(constant));
if (missing.length > 0) {
  throw new Error(`No outline for: ${missing.join(', ')}`);
}

const lines = [];
lines.push('/**');
lines.push(' * districtOutlines.ts — the outlines of the 25 districts of Sri Lanka, keyed by the `District` constant.');
lines.push(' *');
lines.push(' * GENERATED FILE — do not edit. Source: backend/src/main/resources/static/js/districts.js');
lines.push(' * Generated by: node scripts/gen-district-outlines.mjs (from mobile/)');
lines.push(' *');
lines.push(' * Derived (simplified, Douglas-Peucker 0.003 degrees) from geoBoundaries gbOpen LKA ADM2 (Runfola et al., 2020).');
lines.push(' * © OpenStreetMap contributors, ODbL 1.0 — see THIRD-PARTY-NOTICES.md');
lines.push(' *');
lines.push(' * Data only: each district is a list of rings; a ring is a list of [longitude, latitude] points.');
lines.push(' * The lookup of a point is `resolveDistrict` (UC2), not this module.');
lines.push(' */');
lines.push("import type { District } from '../api/types';");
lines.push('');
lines.push('/** One point of an outline: [longitude, latitude] in degrees. */');
lines.push('export type OutlinePoint = readonly [number, number];');
lines.push('');
lines.push('/** A closed ring of points. */');
lines.push('export type OutlineRing = readonly OutlinePoint[];');
lines.push('');
lines.push('/** The outlines of every district: one or more rings each. */');
lines.push('export const DISTRICT_OUTLINES: Readonly<Record<District, readonly OutlineRing[]>> = {');
for (const constant of DISTRICTS) {
  lines.push(`  ${constant}: [`);
  for (const ring of outlines.get(constant)) {
    lines.push(`    ${JSON.stringify(ring)},`);
  }
  lines.push('  ],');
}
lines.push('};');
lines.push('');

writeFileSync(target, lines.join('\n'), 'utf8');
process.stdout.write(`Wrote ${target} (${DISTRICTS.length} districts)\n`);
